#!/usr/bin/env python3
"""Browser test of the system log page of the nextGen UI: reading, export and clearing.

    python3 next_log.py --base http://127.0.0.1:18080 --user Admin --password Admin

REAL on the test CCU: history is generated by logging two system variables and changing them, the page is compared with the
classic log page, the export link is fetched, and the log is CLEARED through the page (a test CCU only; it ends with an empty
log, the state it started in). Mocked answers cover paging of a long log, a failing clear, an expired session and German.
Two logins (the v2 login is rate limited).
"""
import argparse, json, re, sys, time
from datetime import datetime
from playwright.sync_api import sync_playwright

NOISE = ("Synchronous XMLHttpRequest", "Synchrone XMLHttpRequest", "file:///", "favicon")
V1 = """async ([method, sid, params]) => {
  const r = await fetch('/api/homematic.cgi', {method: 'POST', body: JSON.stringify({version: '1.1', method, params: {_session_id_: sid, ...params}})});
  return (await r.json()).result;
}"""
V2LOG = """async ([sid, method]) => {
  const r = await fetch('/api/homematic.cgi/v2/log?limit=1', {method, headers: {'X-Requested-With': 'XMLHttpRequest', 'X-Session-Id': sid}});
  return await r.json();
}"""
PROFILE = {"userId": "1004", "userName": "Admin", "firstName": "Admin", "hasPassword": True, "isNoExpert": True, "language": "", "level": "ADMIN"}


def entry(i, name="Messwert"):
    return {"time": "2026-10-30 %02d:%02d:00" % (i // 60 % 24, i % 60), "name": "%s %d" % (name, i), "kind": "SYSVAR", "datapoint": "", "values": [{"value": "true", "type": "LOGIC", "unit": "", "valueList": "", "valueName0": "aus", "valueName1": "an"}]}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    ap.add_argument("--user", default="Admin")
    ap.add_argument("--password", required=True)
    a = ap.parse_args()
    results, console, sids, urls = [], [], [], []

    def check(name, ok, detail=""):
        results.append(ok)
        print("%s  %s %s" % ("PASS" if ok else "FAIL", name, detail))

    state = {"log": None, "delete": None, "profile": None}

    def on_log(route):
        req = route.request
        urls.append((req.method, req.url.split("/v2")[1]))
        if state["log"] is None and state["delete"] is None:
            return route.continue_()
        if req.method == "DELETE" and state["delete"] is not None:
            status, body = state["delete"]
            return route.fulfill(status=status, content_type="application/json", body=json.dumps(body))
        if req.method == "GET" and state["log"] is not None:
            m = re.search(r"limit=(\d+)&offset=(\d+)", req.url)
            limit, offset = int(m.group(1)), int(m.group(2))
            total = state["log"]
            end = max(0, total - offset); start = max(0, end - limit)
            items = [entry(i) for i in range(end - 1, start - 1, -1)]
            return route.fulfill(status=200, content_type="application/json", body=json.dumps({"total": total, "offset": offset, "limit": limit, "items": items}))
        route.continue_()

    def on_profile(route):
        if state["profile"] is None:
            return route.continue_()
        route.fulfill(status=200, content_type="application/json", body=json.dumps({**PROFILE, **state["profile"]}))

    with sync_playwright() as p:
        browser = p.chromium.launch()
        ctx = browser.new_context(viewport={"width": 1100, "height": 900})
        pg = ctx.new_page()

        def on_response(r):
            try:
                if r.request.method == "POST" and '"Session.login"' in (r.request.post_data or "") and r.ok:
                    sid = r.json().get("result")
                    if isinstance(sid, str):
                        sids.append(sid)
            except Exception:
                pass

        pg.on("response", on_response)
        pg.on("console", lambda m: m.type == "error" and not any(n in m.text for n in NOISE) and console.append(m.text[:140]))
        pg.route("**/v2/log*", on_log)
        pg.route("**/v2/profile", on_profile)
        sid = None
        archived = False
        before = {}

        def v1(method, **params):
            return pg.evaluate(V1, [method, sid, params])

        def rows():
            return [[t.strip() for t in r.locator("td").all_inner_texts()] for r in pg.locator("tbody tr").all()]

        try:
            pg.goto(a.base + "/webui/next/"); pg.wait_for_selector("#user")
            pg.fill("#user", a.user); pg.fill("#password", a.password); pg.keyboard.press("Enter")
            pg.wait_for_selector("aside nav a")
            sid = pg.evaluate("JSON.parse(sessionStorage.getItem('openccu.next.session')).sid")
            v1("ReGa.runScript", script="Write(dom.ClearHistoryData());")  # start from an empty log
            pg.get_by_role("link", name="System log").click(); pg.get_by_role("heading", name="System log").wait_for()
            pg.get_by_text("The system log is empty.").wait_for()
            check("an empty log says so (real answer)", True)
            check("there is nothing to delete yet", pg.get_by_role("button", name="Delete all entries").is_disabled())

            # ---- real history: log two variables and change them
            before = {"Anwesenheit": v1("SysVar.getValueByName", name="Anwesenheit"), "DutyCycle": v1("SysVar.getValueByName", name="DutyCycle")}
            v1("ReGa.runScript", script='dom.GetObject(ID_SYSTEM_VARIABLES).Get("Anwesenheit").DPArchive(true); dom.GetObject(ID_SYSTEM_VARIABLES).Get("DutyCycle").DPArchive(true);'); archived = True
            for kind, val in (("b", 0), ("b", 1), ("f", 12), ("f", 34.5)):
                v1("SysVar.setBool" if kind == "b" else "SysVar.setFloat", name="Anwesenheit" if kind == "b" else "DutyCycle", value=val); time.sleep(1.1)
            pg.get_by_role("button", name="Refresh").click(); pg.wait_for_selector("tbody tr")
            r = rows()
            check("the four changes are in the log, newest first", [x[1] for x in r] == ["DutyCycle", "DutyCycle", "Anwesenheit", "Anwesenheit"], str([x[1:] for x in r]))
            check("the activity is written like a status (value names, two decimals with the unit)", [x[2] for x in r] == ["34.50 %", "12.00 %", "anwesend", "nicht anwesend"], str([x[2] for x in r]))
            check("the count of records is shown", pg.get_by_text("4 of 4 records").is_visible())
            check("no older entries to load", pg.get_by_role("button", name="Show older entries").count() == 0)
            pg.get_by_label("Filter").fill("anwesen")
            check("the filter narrows by name or activity", pg.locator("tbody tr").count() == 2)
            pg.get_by_label("Filter").fill("gibtesnicht")
            check("no match says so", pg.get_by_text("No entry matches the filter.").is_visible())
            pg.get_by_label("Filter").fill("")

            # ---- the classic log page is the reference
            classic = browser.new_page()
            classic.goto(a.base + "/login.htm"); classic.fill("#UserNameShow", a.user); classic.fill("#Password", a.password); classic.keyboard.press("Enter")
            classic.wait_for_load_state("networkidle"); classic.wait_for_timeout(2500)
            classic.evaluate("() => document.getElementById('menuControlPage_TITLE').click()"); classic.wait_for_timeout(400)
            classic.evaluate("() => document.querySelector('#menuControlPage_SUBMENU #submenuSysProtocol').click()"); classic.wait_for_timeout(3500)
            ref = [[re.sub(r"\s+", " ", t.replace("\xa0", " ")).strip() for t in r.locator("td").all_inner_texts()] for r in classic.locator("#histlist tr").all()]
            classic.evaluate("() => { const e=[...document.querySelectorAll('div')].find(d=>d.innerText.trim()==='Logout' && d.children.length===0); e && e.click(); }"); classic.wait_for_timeout(500); classic.close()
            ref = [x for x in ref if len(x) >= 4]
            to_classic = lambda t: datetime.strptime(t, "%b %d, %Y, %I:%M:%S %p").strftime("%d.%m.%Y %H:%M:%S")
            ours = [(to_classic(x[0]), x[1]) for x in r]
            theirs = [(x[0] + " " + x[1], x[2]) for x in ref]
            # the OpenCCU script that keeps the DutyCycle variable current may add an entry of its own while it is logged
            extra = [x for x in theirs if x not in ours]
            check("the classic log shows the same entries (time and name); at most DutyCycle entries of the system script besides", all(o in theirs for o in ours) and all(x[1] == "DutyCycle" for x in extra), "%s / %s" % (sorted(ours), sorted(theirs)))
            check("and the same values for the logic variable", {x[3] for x in ref if x[2] == "Anwesenheit"} == {x[2] for x in r if x[1] == "Anwesenheit"}, str([x[3] for x in ref if x[2] == "Anwesenheit"]))

            # ---- export
            href = pg.get_by_role("link", name="Export").get_attribute("href")
            check("the export link carries the session and the CSV name", re.fullmatch(r"/HistoryBuffer\.csv\?sid=@[A-Za-z0-9]{10}@", href) is not None, href)
            resp = pg.request.get(a.base + href)
            check("ReGa serves the export (HTTP 200) and it names the variables", resp.status == 200 and "Anwesenheit" in resp.text(), "%s %d bytes" % (resp.status, len(resp.text())))

            # ---- cancel and Escape clear nothing
            total_before = pg.evaluate(V2LOG, [sid, "GET"])["total"]
            pg.get_by_role("button", name="Delete all entries").click()
            dlg = pg.get_by_role("dialog")
            check("the dialog warns that it cannot be undone and Cancel has the focus", "cannot be undone" in dlg.inner_text() and pg.evaluate("document.activeElement.textContent") == "Cancel")
            dlg.get_by_role("button", name="Cancel").click(); pg.get_by_role("dialog").wait_for(state="detached")
            pg.get_by_role("button", name="Delete all entries").click(); pg.keyboard.press("Escape"); pg.get_by_role("dialog").wait_for(state="detached")
            check("Cancel and Escape clear nothing (checked on the CCU)", pg.evaluate(V2LOG, [sid, "GET"])["total"] == total_before and total_before >= 4, str(total_before))
            check("focus returns to the button", pg.evaluate("document.activeElement.textContent") == "Delete all entries")

            # ---- clear, really
            pg.get_by_role("button", name="Delete all entries").click(); pg.get_by_role("dialog").get_by_role("button", name="Delete").click(); pg.get_by_role("dialog").wait_for(state="detached")
            pg.get_by_text("The system log was cleared.").wait_for()
            pg.get_by_text("The system log is empty.").wait_for()
            check("the page shows an empty log and says it was cleared", True)
            check("the CCU log is empty (checked through the API)", pg.evaluate(V2LOG, [sid, "GET"])["total"] == 0)
            check("the delete button is off again and the focus went to the filter", pg.get_by_role("button", name="Delete all entries").is_disabled() and pg.evaluate("document.activeElement.id") == "log-filter")

            # ---- mocked: a long log pages by records, a failing clear, an expired session, German
            state["log"] = 450
            pg.get_by_role("button", name="Refresh").click(); pg.get_by_text("200 of 450 records").wait_for()
            del urls[:]
            pg.get_by_role("button", name="Show older entries").click(); pg.get_by_text("400 of 450 records").wait_for()
            pg.get_by_role("button", name="Show older entries").click(); pg.get_by_text("450 of 450 records").wait_for()
            gets = [u for m, u in urls if m == "GET"]
            check("older entries are asked for by records from the newest (offset 200, then 400)", gets == ["/log?limit=200&offset=200", "/log?limit=200&offset=400"], str(gets))
            check("all 450 are listed, newest first, and nothing more to load", pg.locator("tbody tr").count() == 450 and pg.get_by_role("button", name="Show older entries").count() == 0 and "Messwert 449" in pg.locator("tbody tr").first.inner_text())
            for status, body, words, label in ((403, {"error": {"code": 400, "message": "access denied"}}, "not allowed", "no right (403)"), (500, {"error": {"code": 200, "message": "internal secret"}}, "refused", "a server error (500)")):
                state["delete"] = (status, body)
                pg.get_by_role("button", name="Delete all entries").click(); dlg = pg.get_by_role("dialog"); dlg.get_by_role("button", name="Delete").click(); dlg.get_by_role("alert").wait_for()
                msg = dlg.get_by_role("alert").inner_text()
                check("%s: the message stays in the dialog, the log is not touched" % label, words in msg and "secret" not in msg and dlg.get_by_role("button", name="Delete").is_enabled() and pg.locator("tbody tr").count() == 450, msg)
                dlg.get_by_role("button", name="Cancel").click(); pg.get_by_role("dialog").wait_for(state="detached")
            state["delete"] = (200, {"cleared": False, "total": 3})
            pg.get_by_role("button", name="Delete all entries").click(); pg.get_by_role("dialog").get_by_role("button", name="Delete").click()
            pg.get_by_text("could not be cleared completely").wait_for()
            check("a log that is not empty afterwards is told as such", True)
            del console[:]  # the browser logs the deliberate 403/500 as errors

            state["delete"] = None; state["log"] = 3
            pg.get_by_role("button", name="Account menu").click(); pg.get_by_role("menuitemradio", name="Deutsch").click()
            pg.get_by_role("heading", name="Systemprotokoll").wait_for(); pg.get_by_role("button", name="Aktualisieren").click(); pg.get_by_text("3 von 3 Einträgen").wait_for()
            body = pg.inner_text("main")
            check("the page is German", "Datum und Uhrzeit" in body and "Aktivität" in body and "Alle Einträge löschen" in body and "Exportieren" in body and "Status und Bedienung" in body)
            pg.get_by_role("button", name="Alle Einträge löschen").click()
            check("the dialog is German", pg.get_by_role("dialog").get_by_text("Systemprotokoll löschen").is_visible() and "rückgängig" in pg.get_by_role("dialog").inner_text())
            pg.keyboard.press("Escape"); pg.get_by_role("dialog").wait_for(state="detached")
            pg.get_by_role("button", name="Benutzermenü").click(); pg.get_by_role("menuitemradio", name="English").click()
            check("no console errors", not console, str(console))
            state["log"] = None
            pg.route("**/v2/log*", lambda r: r.fulfill(status=401, content_type="application/json", body=json.dumps({"error": {"code": 400, "message": "access denied (session level 0)"}})))
            pg.unroute("**/v2/log*", on_log)
            pg.get_by_role("button", name="Refresh").click(); pg.wait_for_selector("#user", timeout=10000)
            check("an expired session on refresh returns to the sign-in form", pg.evaluate("sessionStorage.length") == 0)
        finally:
            state["log"] = None; state["delete"] = None; state["profile"] = None
            try:
                pg.unroute_all(behavior="ignoreErrors")
            except Exception:
                pass
            try:
                if sid:
                    if archived:
                        v1("ReGa.runScript", script='dom.GetObject(ID_SYSTEM_VARIABLES).Get("Anwesenheit").DPArchive(false); dom.GetObject(ID_SYSTEM_VARIABLES).Get("DutyCycle").DPArchive(false);')
                    if before.get("Anwesenheit") is not None:
                        v1("SysVar.setBool", name="Anwesenheit", value=1 if before["Anwesenheit"] else 0)
                    if before.get("DutyCycle") is not None:
                        v1("SysVar.setFloat", name="DutyCycle", value=float(before["DutyCycle"]))
                    v1("ReGa.runScript", script="Write(dom.ClearHistoryData());")
            except Exception as e:
                print("cleanup problem:", e)
            for s in sids:
                try:
                    pg.request.post(a.base + "/api/homematic.cgi/v2/rpc", headers={"Content-Type": "application/json", "X-Requested-With": "XMLHttpRequest", "X-Session-Id": s},
                                    data=json.dumps({"version": "1.1", "method": "Session.logout", "params": {}, "id": 1}))
                except Exception:
                    pass
            browser.close()
    print("\n%d PASS, %d FAIL" % (results.count(True), results.count(False)))
    return 1 if False in results else 0


if __name__ == "__main__":
    sys.exit(main())
